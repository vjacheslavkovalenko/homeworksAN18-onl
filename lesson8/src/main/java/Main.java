public class Main {
    public static void main(String[] args) {
        // Создаем работников
        Worker worker1 = new Worker("Иван", "Иванов", 3);
        Worker worker2 = new Worker("Петр", "Петров", 2);
        Worker worker3 = new Worker("Сергей", "Сергеев", 5);

        // Создаем директора
        Director director1 = new Director("Алексей", "Алексеев", 10);

        // Печатаем информацию о работниках
        worker1.printInfo();
        worker2.printInfo();
        worker3.printInfo();

        // Назначаем двух работников под управление директора
        director1.add(worker1);
        director1.add(worker2);

        // Печатаем информацию о директоре и его подчиненных
        director1.printInfo();

        // Создаем нового директора с одним работником
        Director director2 = new Director("Мария", "Мариева", 8);
        director2.add(worker3);

        // Добавляем нового директора под управление первого директора
        director1.add(director2);

        // Печатаем информацию о первом директоре после добавления второго
        System.out.println("\nПосле добавления второго директора:");
        director1.printInfo();

        // Проверка, есть ли у первого директора подчиненный с указанным именем
        String searchName = "Сергей Сергеев";
        boolean hasSubordinate = director1.hasSubordinate(searchName);
        System.out.println("\nЕсть ли у " + director1.getFullName() + " подчиненный с именем \"" + searchName + "\": " + hasSubordinate);
    }
}

